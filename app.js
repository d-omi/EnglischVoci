      return `<div class="dir-row"><span class="dir-label">${label}</span><div class="progress-bar"><div class="progress-fill${done ? " complete" : ""}" style="width:${pct}%"></div></div><span class="progress-text">${learned}/${total}</span>${scoreText}</div>`;
