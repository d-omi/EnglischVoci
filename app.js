function saveQuizScore(user, portionIndex, direction, correct, total) {
  const scores = getScores(user);
  if (!scores[portionIndex]) scores[portionIndex] = {};
  scores[portionIndex][direction] = { correct, total, date: new Date().toLocaleDateString("de-CH") };
  saveScores(user, scores);
}
function getQuizScore(user, portionIndex, direction) {
  const scores = getScores(user);
  if (!scores[portionIndex]) return null;
  return scores[portionIndex][direction] || null;
}

function getTermStreak(user, portionIndex, termKey, direction) {
  const progress = getProgress(user);
  const fullKey = "p" + portionIndex + "_" + direction;
  return (progress[fullKey] && progress[fullKey][termKey]) ? progress[fullKey][termKey].streak : 0;
}
function updateTermStreak(user, portionIndex, termKey, direction, correct) {
  const progress = getProgress(user);
  const fullKey = "p" + portionIndex + "_" + direction;
  if (!progress[fullKey]) progress[fullKey] = {};
  if (!progress[fullKey][termKey]) progress[fullKey][termKey] = { streak: 0 };
  if (correct) {
    progress[fullKey][termKey].streak = Math.min(progress[fullKey][termKey].streak + 1, STREAK_GOAL);
  } else {
    progress[fullKey][termKey].streak = 0;
  }
  saveProgress(user, progress);
}
function getPortionProgress(user, portionIndex, direction) {
  const portion = VOCABULARY.portions[portionIndex];
  const progress = getProgress(user);
  const fullKey = "p" + portionIndex + "_" + direction;
  const data = progress[fullKey] || {};
  let learned = 0;
  const total = portion.vocabulary.length;
  for (const term of portion.vocabulary) {
    const termKey = term.english.toLowerCase();
    if (data[termKey] && data[termKey].streak >= STREAK_GOAL) learned++;
  }
  return { learned, total };
}

/* ─── Answer matching ─────────────────────────────────────────── */
function normalize(str) {
  return str.trim().replace(/['\u2018\u2019`]/g, "'").replace(/\s+/g, " ");
}
function getAcceptableAnswers(answerStr) {
  const answers = new Set();
  const parts = answerStr.split(",").map(s => s.trim());
  for (const part of parts) {
    answers.add(normalize(part));
    const withoutParen = part.replace(/\s*\(.*?\)\s*/g, " ").trim();
    if (withoutParen) answers.add(normalize(withoutParen));
    const slashMatch = part.match(/^(.+?)\/-(.+)$/);
    if (slashMatch) { answers.add(normalize(slashMatch[1])); answers.add(normalize(slashMatch[1] + slashMatch[2])); }
    if (part.includes("/") && !part.includes("/-")) {
      for (const sub of part.split("/")) answers.add(normalize(sub));
    }
  }
  return [...answers].filter(a => a.length > 0);
}
function checkUserAnswer(userInput, correctField) {
  const acceptable = getAcceptableAnswers(correctField);
  const input = normalize(userInput);
  return acceptable.some(a => a === input);
}

/* ─── Shuffle ─────────────────────────────────────────────────── */
function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/* ─── Seeded RNG for decorative placement ─────────────────────── */
function mulberry32(a) {
  return function() {
    a |= 0; a = a + 0x6D2B79F5 | 0;
    var t = Math.imul(a ^ a >>> 15, 1 | a);
    t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t;
    return ((t ^ t >>> 14) >>> 0) / 4294967296;
  };
}

/* ─── Game World Builder ──────────────────────────────────────── */
function getBlockX(index) {
  return WORLD_PADDING_LEFT + index * BLOCK_SPACING;
}

function getWorldWidth(numBlocks) {
  return WORLD_PADDING_LEFT + (numBlocks - 1) * BLOCK_SPACING + WORLD_PADDING_RIGHT;
}

function buildWorldHTML(numBlocks, nodeStates, quizWords, direction, portionIndex) {
  const worldW = getWorldWidth(numBlocks);
  const isDeEn = direction === "de-en";
  const theme = getTheme(portionIndex);
  const rng = mulberry32(73 + portionIndex * 17);
  let html = "";

  // Stars (night/space themes)
  if (theme.deco === "stars") {
    const starCount = Math.floor(worldW / 40);
    for (let i = 0; i < starCount; i++) {
      const sx = rng() * worldW;
      const sy = rng() * 120;
      const big = rng() > 0.8;
      html += `<div class="star${big ? " big" : ""}" style="left:${sx}px;top:${sy}px;animation-delay:${rng() * 2}s"></div>`;
    }
  }

  // Clouds (skip for space theme)
  if (theme.deco !== "stars") {
    const cloudCount = Math.max(4, Math.floor(worldW / 350));
    for (let i = 0; i < cloudCount; i++) {
      const cx = 60 + rng() * (worldW - 120);
      const cy = 15 + rng() * 65;
      const type = rng() > 0.5 ? "cloud--1" : "cloud--2";
      html += `<div class="cloud ${type}" style="left:${cx}px;top:${cy}px"></div>`;
    }
  }

  // Hills (background)
  const hillCount = Math.max(3, Math.floor(worldW / 400));
  for (let i = 0; i < hillCount; i++) {
    const hx = rng() * worldW;
    const hw = 120 + rng() * 160;
    const hh = 40 + rng() * 50;
    const isBg = rng() > 0.5;
    html += `<div class="hill${isBg ? " hill--bg" : ""}" style="left:${hx}px;width:${hw}px;height:${hh}px"></div>`;
  }

  // Theme-specific decorations
  const blockPositions = Array.from({ length: numBlocks }, (_, j) => getBlockX(j));
  const isTooClose = (x) => blockPositions.some(bx => Math.abs(bx - x) < 55);

  if (theme.deco === "cactus") {
    for (let i = 0; i < Math.floor(worldW / 250); i++) {
      const cx = 50 + rng() * (worldW - 100);
      if (isTooClose(cx)) continue;
      const ch = 30 + rng() * 25;
      html += `<div class="cactus" style="left:${cx}px;height:${ch}px"></div>`;
    }
  } else if (theme.deco === "snowman") {
    for (let i = 0; i < Math.floor(worldW / 400); i++) {
      const sx = 50 + rng() * (worldW - 100);
      if (isTooClose(sx)) continue;
      html += `<div class="snowman" style="left:${sx}px"><div class="snowman-hat"></div><div class="snowman-top"></div><div class="snowman-bot"></div></div>`;
    }
  } else if (theme.deco === "palm") {
    for (let i = 0; i < Math.floor(worldW / 400); i++) {
      const px = 50 + rng() * (worldW - 100);
      if (isTooClose(px)) continue;
      html += `<div class="palm" style="left:${px}px"><div class="palm-leaf"></div><div class="palm-leaf"></div><div class="palm-leaf"></div><div class="palm-trunk"></div></div>`;
    }
  } else if (theme.deco === "lollipop") {
    const colors = ["#ff6b9d","#c084fc","#67e8f9","#fbbf24","#34d399"];
    for (let i = 0; i < Math.floor(worldW / 300); i++) {
      const lx = 50 + rng() * (worldW - 100);
      if (isTooClose(lx)) continue;
      const col = colors[Math.floor(rng() * colors.length)];
      html += `<div class="lollipop" style="left:${lx}px"><div class="lollipop-top" style="border-color:${col}"></div><div class="lollipop-stick"></div></div>`;
    }
  }

  // Bushes (not for desert/snow/space)
  if (!["cactus","snowman","stars"].includes(theme.deco)) {
    const bushCount = Math.max(3, Math.floor(worldW / 350));
    for (let i = 0; i < bushCount; i++) {
      const bx = 40 + rng() * (worldW - 80);
      if (isTooClose(bx)) continue;
      html += `<div class="bush" style="left:${bx}px"></div>`;
    }
  }

  // Pipes
  for (let i = 0; i < numBlocks - 1; i++) {
    if (rng() > 0.6) {
      const px = getBlockX(i) + 90 + rng() * 60;
      const ph = 40 + rng() * 30;
      html += `<div class="pipe" style="left:${px}px;height:${ph}px"></div>`;
    }
  }

  // Question blocks
  for (let i = 0; i < numBlocks; i++) {
    const bx = getBlockX(i);
    const st = nodeStates[i] || "locked";
    const word = quizWords[i];
    const label = isDeEn ? word.german : word.english;
    const shortLabel = label.length > 14 ? label.slice(0, 12) + "\u2026" : label;
    const inner = st === "correct" ? "" : st === "wrong" ? "" : "?";
    html += `<div class="q-block ${st}" data-block="${i}" style="left:${bx}px">${inner}<span class="q-block-word">${esc(shortLabel)}</span></div>`;
  }

  // Flag pole at the end
  const flagX = getBlockX(numBlocks - 1) + BLOCK_SPACING * 0.7;
  html += `<div class="flag-pole" style="left:${flagX}px"></div>`;

  // Ground (spans full world)
  html += `<div class="ground" style="width:${worldW}px"></div>`;

  // Character
  html += `
    <div class="character" id="game-char" style="left:${state.charPos}px">
      <div class="char-body">
        <div class="char-cap"></div>
        <div class="char-head">
          <div class="char-eye"></div>
        </div>
        <div class="char-shirt"></div>
        <div class="char-legs"></div>
      </div>
    </div>`;

  return { html, worldWidth: worldW };
}

/* ─── Viewport scrolling ──────────────────────────────────────── */
function getScrollOffset(charX) {
  const vw = Math.min(VIEWPORT_WIDTH, window.innerWidth - 24);
  const half = vw / 2;
  let offset = -(charX - half + 17);
  if (offset > 0) offset = 0;
  return offset;
}

