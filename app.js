/* ─── Constants ───────────────────────────────────────────────── */
const STREAK_GOAL = 3;
const STORAGE_PREFIX = "vociQuiz_";

/* ─── State ───────────────────────────────────────────────────── */
let state = {
  screen: "welcome",
  currentUser: null,
  selectedPortion: null,
  direction: "de-en",
  quizWords: [],
  currentIndex: 0,
  answered: false,
  answers: [],
};

/* ─── LocalStorage helpers ────────────────────────────────────── */
function getUsers() {
  return JSON.parse(localStorage.getItem(STORAGE_PREFIX + "users") || "[]");
}

function saveUsers(users) {
  localStorage.setItem(STORAGE_PREFIX + "users", JSON.stringify(users));
}

function getProgress(user) {
  return JSON.parse(localStorage.getItem(STORAGE_PREFIX + "progress_" + user) || "{}");
}

function saveProgress(user, progress) {
  localStorage.setItem(STORAGE_PREFIX + "progress_" + user, JSON.stringify(progress));
}

function getScores(user) {
  return JSON.parse(localStorage.getItem(STORAGE_PREFIX + "scores_" + user) || "{}");
}

function saveScores(user, scores) {
  localStorage.setItem(STORAGE_PREFIX + "scores_" + user, JSON.stringify(scores));
}

function saveQuizScore(user, portionIndex, direction, correct, total) {
  const scores = getScores(user);
  if (!scores[portionIndex]) scores[portionIndex] = {};
  scores[portionIndex][direction] = { correct, total, date: new Date().toLocaleDateString("de-CH") };
  saveScores(user, scores);
}

function getQuizScore(user, portionIndex, direction) {
  const scores = getScores(user);
  if (!scores[portionIndex]) return null;
  return scores[portionIndex][direction] || null;
}

function getTermStreak(user, portionIndex, termKey, direction) {
  const progress = getProgress(user);
  const fullKey = "p" + portionIndex + "_" + direction;
  return (progress[fullKey] && progress[fullKey][termKey]) ? progress[fullKey][termKey].streak : 0;
}

function updateTermStreak(user, portionIndex, termKey, direction, correct) {
  const progress = getProgress(user);
  const fullKey = "p" + portionIndex + "_" + direction;
  if (!progress[fullKey]) progress[fullKey] = {};
  if (!progress[fullKey][termKey]) progress[fullKey][termKey] = { streak: 0 };
  if (correct) {
    progress[fullKey][termKey].streak = Math.min(progress[fullKey][termKey].streak + 1, STREAK_GOAL);
  } else {
    progress[fullKey][termKey].streak = 0;
  }
  saveProgress(user, progress);
}

function getPortionProgress(user, portionIndex, direction) {
  const portion = VOCABULARY.portions[portionIndex];
  const progress = getProgress(user);
  const fullKey = "p" + portionIndex + "_" + direction;
  const data = progress[fullKey] || {};
  let learned = 0;
  const total = portion.vocabulary.length;
  for (const term of portion.vocabulary) {
    const termKey = term.english.toLowerCase();
    if (data[termKey] && data[termKey].streak >= STREAK_GOAL) learned++;
  }
  return { learned, total };
}

/* ─── Answer matching ─────────────────────────────────────────── */
function normalize(str) {
  return str.trim()
    .replace(/['\u2018\u2019`]/g, "'")
    .replace(/\s+/g, " ");
}

function getAcceptableAnswers(answerStr) {
  const answers = new Set();
  const parts = answerStr.split(",").map(s => s.trim());
  for (const part of parts) {
    answers.add(normalize(part));
    const withoutParen = part.replace(/\s*\(.*?\)\s*/g, " ").trim();
    if (withoutParen) answers.add(normalize(withoutParen));
    const slashMatch = part.match(/^(.+?)\/-(.+)$/);
    if (slashMatch) {
      answers.add(normalize(slashMatch[1]));
      answers.add(normalize(slashMatch[1] + slashMatch[2]));
    }
    if (part.includes("/") && !part.includes("/-")) {
      for (const sub of part.split("/")) {
        answers.add(normalize(sub));
      }
    }
  }
  return [...answers].filter(a => a.length > 0);
}

function checkUserAnswer(userInput, correctField) {
  const acceptable = getAcceptableAnswers(correctField);
  const input = normalize(userInput);
  return acceptable.some(a => a === input);
}

/* ─── Shuffle ─────────────────────────────────────────────────── */
function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/* ─── Rendering ───────────────────────────────────────────────── */
const $app = document.getElementById("app");

function render() {
  if (state.currentUser) {
    localStorage.setItem(STORAGE_PREFIX + "lastUser", state.currentUser);
  }
  switch (state.screen) {
    case "welcome":   renderWelcome(); break;
    case "portions":  renderPortions(); break;
    case "quiz":      renderQuiz(); break;
    case "results":   renderResults(); break;
  }
}

