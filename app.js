/* ─── LocalStorage helpers ────────────────────────────────────── */
function getUsers() { return JSON.parse(localStorage.getItem(STORAGE_PREFIX + "users") || "[]"); }
function saveUsers(users) { localStorage.setItem(STORAGE_PREFIX + "users", JSON.stringify(users)); }
function getProgress(user) { return JSON.parse(localStorage.getItem(STORAGE_PREFIX + "progress_" + user) || "{}"); }
function saveProgress(user, progress) { localStorage.setItem(STORAGE_PREFIX + "progress_" + user, JSON.stringify(progress)); }
function getScores(user) { return JSON.parse(localStorage.getItem(STORAGE_PREFIX + "scores_" + user) || "{}"); }
